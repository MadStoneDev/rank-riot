import React from "react";
import {
  Document,
  Page,
  View,
  Text,
  Image,
  StyleSheet,
  renderToBuffer,
} from "@react-pdf/renderer";
import type { ExportColumn, ExportableData } from "@/types/export";
import type { PdfBranding } from "@/utils/pdf-report";
import { RANKRIOT_NAME, RANKRIOT_URL } from "@/utils/export-attribution";

// Server-side branded PDF report (F-E01). Mirrors the client jsPDF layout
// (color header bar + logo + title/subtitle/date, a data table with alternating
// rows, a per-page footer), rendered with @react-pdf/renderer so PDF generation
// — and its plan entitlement — lives on the server and can't be bypassed.

const PRIMARY = "#223971";
const ROW_ALT = "#F5F5FA";

const styles = StyleSheet.create({
  page: { paddingBottom: 36, fontSize: 8, fontFamily: "Helvetica", color: "#333" },
  header: {
    backgroundColor: PRIMARY,
    color: "#fff",
    paddingVertical: 10,
    paddingHorizontal: 16,
    flexDirection: "row",
    alignItems: "center",
    justifyContent: "space-between",
  },
  headerLeft: { flexDirection: "row", alignItems: "center" },
  logo: { width: 28, height: 28, marginRight: 10 },
  title: { fontSize: 14, fontFamily: "Helvetica-Bold" },
  subtitle: { fontSize: 8, marginTop: 3, opacity: 0.85 },
  date: { fontSize: 8, opacity: 0.85, textAlign: "right" },
  table: { marginHorizontal: 10, marginTop: 10 },
  row: { flexDirection: "row" },
  rowAlt: { backgroundColor: ROW_ALT },
  headRow: { backgroundColor: PRIMARY },
  cell: {
    flexGrow: 1,
    flexShrink: 1,
    flexBasis: 0,
    paddingVertical: 3,
    paddingHorizontal: 3,
    borderBottomWidth: 0.5,
    borderBottomColor: "#ddd",
  },
  headCell: { color: "#fff", fontFamily: "Helvetica-Bold" },
  footer: {
    position: "absolute",
    bottom: 12,
    left: 10,
    right: 10,
    flexDirection: "row",
    justifyContent: "space-between",
    fontSize: 7,
    color: "#8c8c8c",
  },
});

function cellText(row: Record<string, unknown>, col: ExportColumn): string {
  const value = row[col.key];
  if (col.formatter) return col.formatter(value);
  if (value === null || value === undefined) return "";
  return String(value);
}

function ReportDocument(props: {
  data: ExportableData;
  columns: ExportColumn[];
  branding?: PdfBranding;
  projectName?: string;
  projectUrl?: string;
}): React.ReactElement {
  const { data, columns, branding, projectName, projectUrl } = props;
  const dateStr = new Date().toLocaleDateString("en-US", { year: "numeric", month: "long", day: "numeric" });
  const title = branding?.businessName ? `${branding.businessName} — SEO Report` : "SEO Report";
  const subtitleParts: string[] = [];
  if (branding?.clientName) subtitleParts.push(`Client: ${branding.clientName}`);
  if (projectName) subtitleParts.push(`Project: ${projectName}`);
  if (projectUrl) subtitleParts.push(projectUrl);

  return (
    <Document>
      <Page size="A4" orientation="landscape" style={styles.page}>
        <View style={styles.header} fixed>
          <View style={styles.headerLeft}>
            {branding?.logoBase64 ? <Image style={styles.logo} src={branding.logoBase64} /> : null}
            <View>
              <Text style={styles.title}>{title}</Text>
              {subtitleParts.length > 0 ? <Text style={styles.subtitle}>{subtitleParts.join("  •  ")}</Text> : null}
            </View>
          </View>
          <Text style={styles.date}>{dateStr}</Text>
        </View>

        <View style={styles.table}>
          <View style={[styles.row, styles.headRow]} fixed>
            {columns.map((col, i) => (
              <Text key={i} style={[styles.cell, styles.headCell]}>{col.header}</Text>
            ))}
          </View>
          {data.map((row, r) => (
            <View key={r} style={r % 2 === 1 ? [styles.row, styles.rowAlt] : styles.row} wrap={false}>
              {columns.map((col, i) => (
                <Text key={i} style={styles.cell}>{cellText(row, col)}</Text>
              ))}
            </View>
          ))}
        </View>

        <View style={styles.footer} fixed>
          <Text render={({ pageNumber, totalPages }) => `Page ${pageNumber} of ${totalPages}`} />
          <Text>{`Generated by ${RANKRIOT_NAME} (${RANKRIOT_URL})`}</Text>
        </View>
      </Page>
    </Document>
  );
}

/** Render the branded PDF report to a Buffer (server-only). */
export async function renderPdfReport(
  data: ExportableData,
  columns: ExportColumn[],
  branding?: PdfBranding,
  projectName?: string,
  projectUrl?: string,
): Promise<Buffer> {
  return renderToBuffer(
    <ReportDocument data={data} columns={columns} branding={branding} projectName={projectName} projectUrl={projectUrl} />,
  );
}
